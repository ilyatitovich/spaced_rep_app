#!/usr/bin/env bash
# Boots the production server image against throwaway Postgres + Redis and
# asserts /health reports ok. Mirrors docker-compose.prod.yml: migrate first,
# then NODE_ENV=production with a password-protected Redis.
#
# Usage: infra/smoke/boot-image.sh            # builds the image first
#        SMOKE_IMAGE=repo/img:tag infra/smoke/boot-image.sh   # use an existing image
set -euo pipefail

cd "$(dirname "${BASH_SOURCE[0]}")/../.."

RUN_ID="smoke-$$"
NETWORK="${RUN_ID}-net"
IMAGE="${SMOKE_IMAGE:-spacedrep-server:smoke}"
ENV_FILE="$(mktemp)"
PG_PASSWORD="$(openssl rand -hex 16)"
REDIS_PASSWORD="$(openssl rand -hex 16)"

cleanup() {
  status=$?
  if [ "$status" -ne 0 ]; then
    echo "::group::server logs"
    docker logs "${RUN_ID}-server" 2>&1 || true
    echo "::endgroup::"
  fi
  docker rm -f "${RUN_ID}-server" "${RUN_ID}-postgres" "${RUN_ID}-redis" >/dev/null 2>&1 || true
  docker network rm "$NETWORK" >/dev/null 2>&1 || true
  rm -f "$ENV_FILE"
  exit "$status"
}
trap cleanup EXIT

if [ -z "${SMOKE_IMAGE:-}" ]; then
  docker build -f apps/server/Dockerfile --target production -t "$IMAGE" .
fi

# Real keys: web-push validates their length at startup. Generated by the image itself.
read -r VAPID_PUBLIC VAPID_PRIVATE < <(docker run --rm "$IMAGE" node -e \
  "const k=require('web-push').generateVAPIDKeys();console.log(k.publicKey+' '+k.privateKey)")

# Only what a doc-following deploy sets. Values are throwaway but production-valid
# (no dev placeholders, no Turnstile test secret, no `*` origin).
cat >"$ENV_FILE" <<EOF
NODE_ENV=production
PORT=3000
CORS_ORIGIN=https://app.smoke.test
DATABASE_URL=postgresql://smoke:${PG_PASSWORD}@${RUN_ID}-postgres:5432/smoke
REDIS_URL=redis://:${REDIS_PASSWORD}@${RUN_ID}-redis:6379
JWT_SECRET=$(openssl rand -hex 32)
OTP_PEPPER=$(openssl rand -hex 32)
TURNSTILE_SECRET_KEY=smoke-turnstile-secret
GOOGLE_CLIENT_ID=smoke-google-client-id
GOOGLE_CLIENT_SECRET=smoke-google-client-secret
GOOGLE_REDIRECT_URIS=https://app.smoke.test/oauth/google/callback
RESEND_API_KEY=re_smoke
EMAIL_FROM=Smoke <smoke@example.com>
WEBAUTHN_RP_ID=app.smoke.test
WEBAUTHN_RP_NAME=Smoke
WEBAUTHN_ORIGIN=https://app.smoke.test
VAPID_PUBLIC_KEY=${VAPID_PUBLIC}
VAPID_PRIVATE_KEY=${VAPID_PRIVATE}
VAPID_SUBJECT=mailto:smoke@example.com
EOF

docker network create "$NETWORK" >/dev/null

docker run -d --name "${RUN_ID}-postgres" --network "$NETWORK" \
  -e POSTGRES_USER=smoke -e POSTGRES_PASSWORD="$PG_PASSWORD" -e POSTGRES_DB=smoke \
  postgres:17-alpine >/dev/null
docker run -d --name "${RUN_ID}-redis" --network "$NETWORK" \
  redis:7-alpine redis-server --requirepass "$REDIS_PASSWORD" >/dev/null

echo "Waiting for Postgres..."
# pg_isready is true while initdb's temporary server is up. That server then
# exits and deletes the socket. Wait until init has finished and the real
# server accepts connections.
ready=0
for _ in $(seq 1 60); do
  if docker logs "${RUN_ID}-postgres" 2>&1 | grep -F "PostgreSQL init process complete" >/dev/null \
    && docker exec "${RUN_ID}-postgres" pg_isready -U smoke -d smoke >/dev/null 2>&1; then
    ready=1
    break
  fi
  sleep 1
done
if [ "$ready" -ne 1 ]; then
  echo "Postgres did not become ready" >&2
  docker logs "${RUN_ID}-postgres" >&2 || true
  exit 1
fi

echo "Running migrations..."
docker run --rm --network "$NETWORK" --env-file "$ENV_FILE" "$IMAGE" \
  pnpm prisma:migrate:deploy

echo "Starting server..."
docker run -d --name "${RUN_ID}-server" --network "$NETWORK" --env-file "$ENV_FILE" \
  "$IMAGE" >/dev/null

PROBE="fetch('http://127.0.0.1:3000/health').then(async r=>{const b=await r.json();console.log(JSON.stringify(b));process.exit(r.ok&&b.status==='ok'?0:1)}).catch(e=>{console.error(String(e));process.exit(1)})"
for _ in $(seq 1 60); do
  if docker exec "${RUN_ID}-server" node -e "$PROBE"; then
    echo "OK: image booted and /health is ok"
    exit 0
  fi
  if [ "$(docker inspect -f '{{.State.Running}}' "${RUN_ID}-server")" != "true" ]; then
    echo "FAIL: server container exited" >&2
    exit 1
  fi
  sleep 2
done

echo "FAIL: /health did not become ok" >&2
exit 1
